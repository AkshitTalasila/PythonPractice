class Vehicle:

    def __init__(self, make = "Unkown", model = "Unkown", year = 0000):

        self.make = make
        self.model = model
        self.year = year

    def get_make(self):

        return self.make

    def get_model(self):

        return self.model

    def get_year(self):

        return self.year

